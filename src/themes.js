export const THEME_KEYS = Object.keys(THEMES)
export const DEFAULT_THEME = 'claude-web'

// Apply a theme to the document root by setting CSS custom properties
export function applyTheme(themeKey) {
  const theme = THEMES[themeKey] || THEMES[DEFAULT_THEME]
  const root = document.documentElement
  for (const [prop, value] of Object.entries(theme.vars)) {
    root.style.setProperty(prop, value)
  }
  root.dataset.theme = themeKey
}

// Get a CSS variable string for inline injection (static export)
export function themeToCSS(themeKey) {
  const theme = THEMES[themeKey] || THEMES[DEFAULT_THEME]
  const vars = Object.entries(theme.vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')
  return `:root {\n${vars}\n}`
}

// Get all themes as a CSS block using [data-theme="key"] attribute selectors.
// All themes coexist in one stylesheet; switching is done by setting data-theme
// on <html>. Contrast with themeToCSS(), which writes a single :root block for
// static exports where only one theme is ever active.
export function allThemesToCSS() {
  return Object.entries(THEMES).map(([key, theme]) => {
    const vars = Object.entries(theme.vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')
    return `[data-theme="${key}"] {\n${vars}\n}`
  }).join('\n\n')
}
